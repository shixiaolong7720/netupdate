"""Feature loading and train-only hard-example sampling for FAH v2.

NPZ features use the existing mfcc/logmel/mfcc_gate keys. Durations describe
independent audio segments; they are not a substitute for streaming timestamps.
No WAV is moved, rewritten, or generated by this module.
"""
from __future__ import annotations

import csv
import math
from pathlib import Path
from typing import Iterable, Sequence

import numpy as np
import torch
from torch.utils.data import Dataset, Sampler

from fah_labels_v2 import LabelAudit, inspect_label_metadata


def _positive_duration(value: object, context: str) -> float:
    array = np.asarray(value)
    if array.size != 1:
        raise ValueError(f"{context}: duration_sec must contain exactly one value")
    duration = float(array.reshape(-1)[0])
    if not math.isfinite(duration) or duration <= 0.0:
        raise ValueError(f"{context}: duration_sec must be finite and > 0")
    return duration


def _load_duration_manifest(path: str | Path) -> dict[str, float]:
    durations: dict[str, float] = {}
    with Path(path).open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames or not {"sid", "duration_sec"}.issubset(reader.fieldnames):
            raise ValueError(f"{path}: CSV needs sid,duration_sec columns")
        for row_number, row in enumerate(reader, start=2):
            sid = str(row["sid"]).strip().replace("\\", "/")
            if not sid or sid in durations:
                raise ValueError(f"{path}:{row_number}: empty or duplicate sid: {sid!r}")
            durations[sid] = _positive_duration(row["duration_sec"], f"{path}:{row_number}")
    return durations


class FeatureDataset(Dataset):
    """Read ``root/ID_*/*.npz`` in a stable order.

    Items are ``mfcc, logmel, mfcc_gate, label, cid, sid, index``. Features have
    shapes [1,20,T], [1,40,T], [1,60,T]. ``sid`` is relative to root, e.g.
    ``ID_0_wake/example.npz``. A supplied CSV manifest is authoritative and must
    cover every selected file. Otherwise duration_sec in each NPZ is preferred
    over the explicitly reported default duration.
    """

    def __init__(
        self,
        root: str | Path,
        default_duration_sec: float = 1.5,
        duration_manifest: str | Path | None = None,
        label_policy: str = "strict",
        label_audit_path: str | Path | None = None,
    ):
        self.root = Path(root).expanduser().resolve()
        self.root_dir = str(self.root)
        if not self.root.is_dir():
            raise FileNotFoundError(f"Feature root does not exist: {self.root}")
        self.default_duration_sec = _positive_duration(default_duration_sec, "default_duration_sec")
        self.label_policy = label_policy
        manifest = _load_duration_manifest(duration_manifest) if duration_manifest is not None else None
        paths, class_ids, sids, durations, duration_sources = [], [], [], [], []
        excluded_noise = 0
        audit = LabelAudit(label_policy, label_audit_path)
        try:
            for folder in sorted(self.root.iterdir(), key=lambda p: p.name):
                if not folder.is_dir() or not folder.name.startswith("ID_"):
                    continue
                if folder.name.casefold() == "id_25_noise":
                    excluded_noise += sum(1 for _ in folder.glob("*.npz"))
                    continue
                parts = folder.name.split("_")
                try:
                    cid = int(parts[1])
                except (ValueError, IndexError):
                    continue
                if cid < 0:
                    raise ValueError(f"Negative class ID is invalid: {folder}")
                for path in sorted(folder.glob("*.npz"), key=lambda p: p.name):
                    sid = path.relative_to(self.root).as_posix()
                    # Read metadata once during the existing directory scan.
                    # No feature array is materialized here; report all label
                    # conflicts before enrollment, calibration or optimization.
                    with np.load(path, allow_pickle=False) as data:
                        audit.record(data, cid, path, sid)
                        if manifest is not None:
                            if sid not in manifest:
                                raise ValueError(f"Duration manifest has no entry for {sid!r} in {self.root}")
                            duration, source = manifest[sid], "manifest"
                        elif "duration_sec" in data.files:
                            duration = _positive_duration(data["duration_sec"], str(path))
                            source = "npz"
                        else:
                            duration, source = self.default_duration_sec, "default"
                    paths.append(str(path))
                    class_ids.append(cid)
                    sids.append(sid)
                    durations.append(duration)
                    duration_sources.append(source)
                    if len(paths) % 10000 == 0:
                        print(f"[Metadata scan] {self.root.name}: {len(paths)} files", flush=True)
        finally:
            audit.close()
        self.label_audit = audit.finish()

        if not paths:
            raise ValueError(f"No usable NPZ features under {self.root}")
        self.paths = np.asarray(paths, dtype=object)
        self.file_paths = self.paths  # compatibility for diagnostics
        self.class_ids = np.asarray(class_ids, dtype=np.int64)
        self.labels = (self.class_ids == 0).astype(np.float32)
        self.sids = np.asarray(sids, dtype=object)
        self.durations_sec = np.asarray(durations, dtype=np.float64)
        self.duration_sources = np.asarray(duration_sources, dtype=object)
        self.duration_source_counts = {
            source: int(np.sum(self.duration_sources == source))
            for source in ("manifest", "npz", "default")
        }
        # One shape probe establishes a common T without caching the dataset.
        with np.load(self.paths[0], allow_pickle=False) as first:
            if "mfcc" not in first.files:
                raise ValueError(f"{self.paths[0]}: missing mfcc feature")
            shape = first["mfcc"].shape
            if len(shape) != 2 or shape[0] != 20 or shape[1] < 1:
                raise ValueError(f"{self.paths[0]}: mfcc must have shape [20,T], got {shape}")
            self.frames = int(shape[1])
        counts = {int(cid): int(np.sum(self.class_ids == cid)) for cid in np.unique(self.class_ids)}
        print(f"[Features] root={self.root} samples={len(self)} frames={self.frames} classes={counts}")
        print(f"[Durations] sources={self.duration_source_counts}; excluded ID_25_noise={excluded_noise}")
        if self.duration_source_counts["default"]:
            print(
                f"[Duration assumption] {self.duration_source_counts['default']} independent segments "
                f"use {self.default_duration_sec:g}s each. Supply a duration manifest if this is inaccurate."
            )

    def __len__(self) -> int:
        return int(len(self.paths))

    def __getitem__(self, index: int):
        index = int(index)
        if index < 0 or index >= len(self):
            raise IndexError(index)
        path = str(self.paths[index])
        features = []
        with np.load(path, allow_pickle=False) as data:
            for key, channels in (("mfcc", 20), ("logmel", 40), ("mfcc_gate", 60)):
                if key not in data.files:
                    raise ValueError(f"{path}: missing {key!r}")
                array = np.asarray(data[key], dtype=np.float32)
                expected = (channels, self.frames)
                if array.shape != expected:
                    raise ValueError(f"{path}: {key} must have shape {expected}, got {array.shape}")
                if not np.all(np.isfinite(array)):
                    raise ValueError(f"{path}: {key} contains NaN or infinity")
                features.append(torch.from_numpy(np.ascontiguousarray(array)).unsqueeze(0))
            if self.label_policy == "strict":
                # Detect changes to metadata after the constructor audit too.
                issues = inspect_label_metadata(data, int(self.class_ids[index]))
                if issues:
                    first = issues[0]
                    raise ValueError(f"{path}: stored {first['field']}={first['stored_value']} "
                                     f"disagrees with folder expected {first['folder_expected']}; "
                                     "metadata changed after the preflight label audit")
        return (
            *features,
            torch.tensor(float(self.labels[index]), dtype=torch.float32),
            int(self.class_ids[index]),
            str(self.sids[index]),
            index,
        )


class TrainingPoolDataset(Dataset):
    """Merge explicit training/adaptation roots, preserving globally unique IDs.

    Validation and test datasets must never be passed here. The caller owns
    directory/speaker/source-recording separation checks.
    """

    def __init__(self, datasets: Sequence[FeatureDataset]):
        self.datasets = list(datasets)
        if not self.datasets:
            raise ValueError("TrainingPoolDataset requires at least one dataset")
        roots = [dataset.root for dataset in self.datasets]
        if len(set(roots)) != len(roots):
            raise ValueError("The same feature root cannot be included twice in the training pool")
        frames = {dataset.frames for dataset in self.datasets}
        if len(frames) != 1:
            raise ValueError(f"Training roots have different frame counts: {sorted(frames)}")
        self.frames = self.datasets[0].frames
        self.cumulative_sizes = np.cumsum([len(dataset) for dataset in self.datasets], dtype=np.int64)
        self.paths = np.concatenate([dataset.paths for dataset in self.datasets])
        self.file_paths = self.paths
        self.class_ids = np.concatenate([dataset.class_ids for dataset in self.datasets])
        self.labels = np.concatenate([dataset.labels for dataset in self.datasets])
        self.durations_sec = np.concatenate([dataset.durations_sec for dataset in self.datasets])
        self.duration_sources = np.concatenate([dataset.duration_sources for dataset in self.datasets])
        self.sids = np.asarray(
            [f"root_{root_index:02d}/{sid}" for root_index, dataset in enumerate(self.datasets) for sid in dataset.sids],
            dtype=object,
        )

    def __len__(self) -> int:
        return int(self.cumulative_sizes[-1])

    def __getitem__(self, index: int):
        index = int(index)
        if index < 0 or index >= len(self):
            raise IndexError(index)
        root_index = int(np.searchsorted(self.cumulative_sizes, index, side="right"))
        offset = 0 if root_index == 0 else int(self.cumulative_sizes[root_index - 1])
        item = self.datasets[root_index][index - offset]
        return (*item[:5], str(self.sids[index]), index)


class EpisodeBatchSampler(Sampler[list[int]]):
    """Exact NxM GE2E episodes alternating with heterogeneous background batches.

    Confusable episodes always contain ID0 plus N-1 distinct IDs from 1..20,
    with exactly M samples per class. Background batches keep M wake examples
    and distribute (N-1)*M examples over available IDs 21/22/24/25. ID23 remains
    the environmental Gate's responsibility; independent ID25 confusables enter
    heterogeneous background rejection, never a single GE2E class. Mining queues
    are refreshed exclusively from this training dataset.
    """

    def __init__(
        self,
        dataset: FeatureDataset | TrainingPoolDataset,
        n_classes: int = 10,
        m_utterances: int = 12,
        batches_per_epoch: int = 800,
        seed: int = 42,
        warmup_epochs: int = 10,
        hard_positive_fraction: float = 0.25,
        hard_negative_fraction: float = 0.25,
    ):
        if n_classes < 2 or m_utterances < 2 or batches_per_epoch < 1 or warmup_epochs < 0:
            raise ValueError("Require n_classes>=2, m_utterances>=2, batches_per_epoch>=1, warmup_epochs>=0")
        for name, value in (("hard_positive_fraction", hard_positive_fraction), ("hard_negative_fraction", hard_negative_fraction)):
            if not math.isfinite(value) or not 0.0 <= value <= 1.0:
                raise ValueError(f"{name} must be in [0,1]")
        self.dataset = dataset
        self.n_classes = int(n_classes)
        self.m_utterances = int(m_utterances)
        self.batches_per_epoch = int(batches_per_epoch)
        self.seed = int(seed)
        self.warmup_epochs = int(warmup_epochs)
        self.hard_positive_fraction = float(hard_positive_fraction)
        self.hard_negative_fraction = float(hard_negative_fraction)
        self.by_cid = {int(cid): np.flatnonzero(dataset.class_ids == cid) for cid in np.unique(dataset.class_ids)}
        if len(self.by_cid.get(0, ())) < 2:
            raise ValueError("Training pool needs at least two distinct ID_0 wake samples")
        self.hard_ids = [cid for cid in range(1, 21) if len(self.by_cid.get(cid, ())) > 0]
        if len(self.hard_ids) < self.n_classes - 1:
            raise ValueError(
                f"Only {len(self.hard_ids)} hard classes are available; n_classes={self.n_classes} "
                f"requires {self.n_classes - 1}. Set --n-classes explicitly for a smaller dataset."
            )
        available_background = [(cid, weight) for cid, weight in ((21, 0.5), (22, 0.3), (24, 0.2), (25, 0.3)) if len(self.by_cid.get(cid, ())) > 0]
        if not available_background:
            raise ValueError("Training pool needs at least one background class from ID_21, ID_22, ID_24, ID_25")
        self.background_ids = [cid for cid, _ in available_background]
        self.background_weights = np.asarray([weight for _, weight in available_background], dtype=np.float64)
        self.background_weights /= self.background_weights.sum()
        self.hard_positive_indices = np.asarray([], dtype=np.int64)
        self.hard_negative_indices: dict[int, np.ndarray] = {}
        self.last_mining_summary: dict[str, object] = {}
        self.epoch = 1

    def __len__(self) -> int:
        return self.batches_per_epoch

    def set_epoch(self, epoch: int) -> None:
        if int(epoch) < 1:
            raise ValueError("Epoch numbering starts at 1")
        self.epoch = int(epoch)

    def update_mining(
        self,
        scores: np.ndarray,
        operating_thresholds: Sequence[float],
        gate_probs: np.ndarray | None = None,
    ) -> dict[str, object]:
        """Refresh low-wake and high/boundary-negative queues from KWS scores.

        Scores follow dataset index order; NaN marks an unobserved sample in a
        bounded mining pass. Only observed samples enter queues, while every
        sample remains eligible for random sampling. Gate probabilities follow
        the same convention; examples are not discarded merely because the Gate
        rejects them, so the Gate cannot hide weaknesses in the KWS branch.
        """
        scores = np.asarray(scores, dtype=np.float64).reshape(-1)
        if len(scores) != len(self.dataset) or np.any(np.isinf(scores)):
            raise ValueError("Mining scores need one entry per training index; use NaN for unobserved entries, never infinity")
        observed = np.isfinite(scores)
        if np.any((scores[observed] < 0.0) | (scores[observed] > 1.0)):
            raise ValueError("Observed mining scores must be unit cosine scores in [0,1]")
        thresholds = np.asarray(operating_thresholds, dtype=np.float64).reshape(-1)
        if not np.all(np.isfinite(thresholds)):
            raise ValueError("Operating thresholds must be finite")
        thresholds = thresholds[(thresholds >= 0.0) & (thresholds <= 1.0)]
        if gate_probs is not None:
            gate_probs = np.asarray(gate_probs, dtype=np.float64).reshape(-1)
            finite_gates = np.isfinite(gate_probs)
            if len(gate_probs) != len(scores) or np.any(np.isinf(gate_probs)) or np.any((gate_probs[finite_gates] < 0.0) | (gate_probs[finite_gates] > 1.0)):
                raise ValueError("gate_probs must be probabilities or NaN at unobserved indices, never infinity")
        wake = self.by_cid[0][observed[self.by_cid[0]]]
        n_wake = int(math.ceil(0.25 * len(wake)))
        self.hard_positive_indices = wake[np.argsort(scores[wake], kind="stable")[:n_wake]]
        self.hard_negative_indices = {}
        for cid in self.hard_ids + self.background_ids:
            pool = self.by_cid[cid][observed[self.by_cid[cid]]]
            if len(pool) == 0:
                continue
            count = max(1, int(math.ceil(0.25 * len(pool))))
            # Half the queue is the high-score tail. Remaining slots cover the
            # nearest examples to both operating thresholds in round-robin order.
            high = pool[np.argsort(-scores[pool], kind="stable")]
            selected = high[: max(1, (count + 1) // 2)].tolist()
            seen = set(selected)
            if thresholds.size:
                boundary_orders = [pool[np.argsort(np.abs(scores[pool] - threshold), kind="stable")] for threshold in thresholds]
                for rank in range(len(pool)):
                    for order in boundary_orders:
                        candidate = int(order[rank])
                        if candidate not in seen and len(selected) < count:
                            selected.append(candidate)
                            seen.add(candidate)
                    if len(selected) >= count:
                        break
            if len(selected) < count:
                for candidate in high:
                    if int(candidate) not in seen:
                        selected.append(int(candidate))
                        seen.add(int(candidate))
                    if len(selected) >= count:
                        break
            self.hard_negative_indices[cid] = np.asarray(selected, dtype=np.int64)
        self.last_mining_summary = {
            "hard_positive_count": len(self.hard_positive_indices),
            "hard_negative_counts": {str(cid): len(indices) for cid, indices in self.hard_negative_indices.items()},
            "observed_count": int(observed.sum()),
            "dataset_count": len(scores),
            "observed_counts_by_cid": {str(cid): int(observed[indices].sum()) for cid, indices in self.by_cid.items()},
            "operating_thresholds": thresholds.tolist(),
        }
        return self.last_mining_summary

    @staticmethod
    def _choice(rng: np.random.RandomState, pool: np.ndarray, n: int) -> np.ndarray:
        if n == 0:
            return np.asarray([], dtype=np.int64)
        if len(pool) == 0:
            raise ValueError("Cannot sample from an empty class")
        return rng.choice(pool, size=n, replace=len(pool) < n).astype(np.int64)

    def _sample_class(self, rng: np.random.RandomState, cid: int, n: int) -> list[int]:
        pool = self.by_cid[cid]
        if cid == 0:
            queue, fraction = self.hard_positive_indices, self.hard_positive_fraction
        else:
            queue, fraction = self.hard_negative_indices.get(cid, np.asarray([], dtype=np.int64)), self.hard_negative_fraction
        n_hard = min(n, int(round(n * fraction))) if len(queue) else 0
        # When enough class examples exist, hard/random portions are disjoint.
        if len(pool) >= n:
            n_hard = min(n_hard, len(queue))
            hard = self._choice(rng, queue, n_hard)
            remaining = pool[~np.isin(pool, hard)]
            random = self._choice(rng, remaining, n - n_hard)
        else:
            hard = self._choice(rng, queue, n_hard)
            random = self._choice(rng, pool, n - n_hard)
        result = np.concatenate((hard, random))
        rng.shuffle(result)
        return result.tolist()

    def _background_counts(self, total: int) -> np.ndarray:
        raw = total * self.background_weights
        counts = np.floor(raw).astype(np.int64)
        remainder = total - int(counts.sum())
        order = np.argsort(-(raw - counts), kind="stable")
        counts[order[:remainder]] += 1
        return counts

    def __iter__(self) -> Iterable[list[int]]:
        rng = np.random.RandomState(self.seed + 1009 * self.epoch)
        for step in range(self.batches_per_epoch):
            confusable = self.epoch <= self.warmup_epochs or step % 2 == 0
            batch = self._sample_class(rng, 0, self.m_utterances)
            if confusable:
                selected_ids = rng.choice(self.hard_ids, size=self.n_classes - 1, replace=False)
                for cid in selected_ids:
                    batch.extend(self._sample_class(rng, int(cid), self.m_utterances))
            else:
                counts = self._background_counts((self.n_classes - 1) * self.m_utterances)
                background = []
                for cid, count in zip(self.background_ids, counts):
                    background.extend(self._sample_class(rng, cid, int(count)))
                rng.shuffle(background)
                batch.extend(background)
            if len(batch) != self.n_classes * self.m_utterances:
                raise RuntimeError("Episode sampler violated its NxM batch-size contract")
            yield batch
